// Run with: PGLITE_MODULE=/path/to/@electric-sql/pglite/dist/index.js node --test tests/split-workflow.mjs
// Executes the actual migration against isolated PostgreSQL, never the live database.
import { readFileSync } from 'node:fs';
import { test } from 'node:test';
import assert from 'node:assert/strict';
const { PGlite } = await import(process.env.PGLITE_MODULE || '@electric-sql/pglite');
const db = new PGlite();
const id = n => `00000000-0000-0000-0000-${String(n).padStart(12,'0')}`;
const [project, track, lead, a, b, outsider, role, member] = [1,2,3,4,5,6,7,8].map(id);
await db.exec(`
create role anon; create role authenticated; create role service_role;
create schema auth;
create function auth.role() returns text language sql as $$select coalesce(current_setting('test.auth_role',true),'service_role')$$;
create table public.projects(id uuid primary key);
create table public.profiles(id uuid primary key);
create table public.tracks(id uuid primary key,project_id uuid,working_title text);
create table public.roles(id uuid primary key,name text);
create table public.project_members(id uuid primary key default gen_random_uuid(),project_id uuid,user_id uuid,status text);
create table public.member_roles(project_member_id uuid,role_id uuid);
create function public.is_project_member(uuid) returns boolean language sql as $$select true$$;
create table public.track_splits(id uuid primary key default gen_random_uuid(),project_id uuid,track_id uuid,contributor_id uuid,contribution_role text,percentage numeric(5,2),status text,confirmed_at timestamptz,created_by uuid,created_at timestamptz default now(),updated_at timestamptz default now(),unique(track_id,contributor_id,contribution_role));
create table public.track_rights_checks(project_id uuid,track_id uuid,check_key text,status text,evidence_note text,updated_by uuid,updated_at timestamptz,unique(track_id,check_key));
create table public.notifications(id uuid default gen_random_uuid(),user_id uuid,project_id uuid,type text,title text,body text,entity_type text,entity_id uuid,action_url text);
create table public.platform_events(user_id uuid,project_id uuid,event_name text,category text,entity_type text,entity_id uuid,metadata jsonb);
insert into projects values('${project}'); insert into profiles values('${lead}'),('${a}'),('${b}'),('${outsider}');
insert into tracks values('${track}','${project}','Test song');
insert into roles values('${role}','Project Admin');
insert into project_members(id,project_id,user_id,status) values('${member}','${project}','${lead}','active'),(gen_random_uuid(),'${project}','${a}','active'),(gen_random_uuid(),'${project}','${b}','active');
insert into member_roles values('${member}','${role}');
`);
await db.exec(readFileSync(new URL('../supabase/migrations/20260927173036_member_split_workflow.sql',import.meta.url),'utf8'));
const call = (actor, op, version, rows=[], split=null, reason=null) => db.query('select manage_split_plan($1,$2,$3,$4,$5,$6::jsonb,$7,$8) as result',[actor,project,track,op,version,JSON.stringify(rows),split,reason]);
const rows = (x=40,y=60) => [{contributor_id:a,contribution_role:'Writer',percentage:String(x)},{contributor_id:b,contribution_role:'Producer',percentage:String(y)}];
const query = async sql => (await db.query(sql)).rows;

test('split workflow: validation, atomic revisions, permissions and stale approvals', async () => {
  await assert.rejects(call(outsider,'save',0,rows()),/Active project/);
  await assert.rejects(call(a,'save',0,rows()),/management access/);
  await assert.rejects(call(lead,'save',0,rows(60,60)),/exceed/);
  await assert.rejects(call(lead,'save',0,rows('NaN',60)),/decimal/);
  await assert.rejects(call(lead,'save',0,[rows()[0],{...rows()[0],contribution_role:' writer '}]),/duplicate/);
  await assert.rejects(call(lead,'save',0,[{...rows()[0],contributor_id:outsider}]),/active project member/);
  await call(lead,'save',0,rows(30,60));
  await assert.rejects(call(lead,'send',1),/exactly 100/);
  await call(lead,'save',1,rows());
  await assert.rejects(call(lead,'save',1,rows()),/changed/);
  await call(lead,'send',2);
  await assert.rejects(call(lead,'send',3),/already been sent/);
  let saved = await query('select * from track_splits order by percentage');
  await assert.rejects(call(a,'confirm',3,[],saved[1].id),/no longer awaiting/);
  await call(a,'confirm',3,[],saved[0].id);
  await call(b,'confirm',3,[],saved[1].id);
  assert.equal((await query('select status from track_split_plans'))[0].status,'confirmed');
  assert.equal((await query('select status from track_rights_checks'))[0].status,'clear');
  await call(lead,'save',3,rows(50,50));
  assert.ok((await query('select status,confirmed_at from track_splits')).every(r=>r.status==='draft'&&r.confirmed_at===null));
  assert.equal((await query('select status from track_rights_checks'))[0].status,'pending');
  await assert.rejects(call(a,'confirm',3,[],saved[0].id),/changed/);
  await call(lead,'send',4);
  saved = await query('select * from track_splits');
  await call(a,'request_change',5,[],saved.find(r=>r.contributor_id===a).id,'Please review my writer share.');
  assert.ok((await query('select status from track_splits')).every(r=>r.status==='draft'));
  assert.equal((await query('select version from track_split_plans'))[0].version,6);
  assert.ok((await query('select * from notifications')).every(r=>r.action_url===`/splits?track=${track}`));
  assert.ok((await query('select metadata from platform_events')).every(r=>Array.isArray(r.metadata.previous_rows)));
  await db.exec("set test.auth_role='authenticated'");
  await assert.rejects(call(lead,'save',6,rows()),/Server access required/);
  await db.exec("set test.auth_role='service_role'");
  const privileges = await query("select has_function_privilege('authenticated','public.manage_split_plan(uuid,uuid,uuid,text,integer,jsonb,uuid,text)','execute') as browser_rpc,has_table_privilege('authenticated','public.track_splits','update') as browser_write");
  assert.equal(privileges[0].browser_rpc,false); assert.equal(privileges[0].browser_write,false);
  // A downstream failure must roll back percentages, version and all approvals.
  await db.exec("create function fail_event() returns trigger language plpgsql as $$begin raise exception 'test event failure'; end$$; create trigger fail_event before insert on platform_events for each row execute function fail_event();");
  await assert.rejects(call(lead,'save',6,rows(20,80)),/test event failure/);
  assert.equal((await query('select version from track_split_plans'))[0].version,6);
  assert.deepEqual((await query('select percentage::text from track_splits order by percentage')).map(r=>r.percentage),['50.00','50.00']);
  await db.exec(readFileSync(new URL('../supabase/migrations/20260927173946_music_helper_usage.sql',import.meta.url),'utf8'));
  for(let i=0;i<20;i++) assert.equal((await db.query('select reserve_music_helper_request($1) as allowed',[a])).rows[0].allowed,true);
  assert.equal((await db.query('select reserve_music_helper_request($1) as allowed',[a])).rows[0].allowed,false);
  assert.equal((await db.query('select reserve_music_helper_request($1) as allowed',[outsider])).rows[0].allowed,false);
  await db.close();
});
