 assert.match(index,/option value="Unclassified">Needs classification/);
 assert.match(detail,/name="account_kind"/);
 assert.match(detail,/>Fan \/ Listener<\/option>/);
 assert.match(actions,/category==="fan"\?\["Fan"\]:selected/);
